#!/usr/bin/env bash
#
# Deploy this project to the Raspberry Pi.
#
#   ./deploy.sh              # deploy
#   ./deploy.sh --dry-run    # show what would change, touch nothing
#   ./deploy.sh --prune      # also delete Pi files no longer in the repo
#
# The Pi's copy is NOT a git clone -- it's a plain directory kept in sync from
# here with rsync. So this script stamps the deployed commit into
# .deployed-commit on the Pi, which is the only record of what's running there.
#
# Secrets and machine-local config (.env, blind-sensor-map.json) live only on
# the Pi and are never transferred or deleted.

set -euo pipefail

PI_HOST="${PI_HOST:-pi@pi.local}"
PI_DIR="${PI_DIR:-/home/pi/ring-local-enhancements}"
PM2_APP="${PM2_APP:-ring-local-enhancements}"

DRY_RUN=0
PRUNE=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    --prune)   PRUNE=1 ;;
    -h|--help) sed -n '2,16p' "$0" | sed 's/^#//'; exit 0 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

cd "$(dirname "$0")"

say()  { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
fail() { printf '\n\033[31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

# Never transferred. .env and blind-sensor-map.json are the Pi's own; the rest
# is either local build state or meaningless on the target.
EXCLUDES=(
  --exclude .git
  --exclude node_modules
  --exclude .env
  --exclude .env.pi.bak
  --exclude blind-sensor-map.json
  --exclude .DS_Store
  --exclude scratchpad
)

# --- Preflight -------------------------------------------------------------
# Deploying a dirty tree ships code that exists nowhere in history, which makes
# the commit stamp on the Pi a lie. Refuse.

say "Preflight"

# Untracked files get rsynced too, so they count as dirty -- otherwise the
# commit stamped on the Pi wouldn't describe what actually landed there.
# Ignored files (.env, node_modules) are excluded by --porcelain.
if [ -n "$(git status --porcelain)" ]; then
  git status --short
  fail "Working tree is dirty (including untracked files). Commit, stash, or gitignore them first."
fi

COMMIT="$(git rev-parse HEAD)"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"
echo "  commit:  ${COMMIT:0:8} on ${BRANCH}"

# Warn (don't block) if the commit isn't on the remote -- deploying something
# unpushed is legitimate in a pinch, but you should know you're doing it.
if git remote | head -1 | grep -q .; then
  REMOTE="$(git remote | head -1)"
  if git fetch --quiet "$REMOTE" 2>/dev/null && \
     ! git merge-base --is-ancestor "$COMMIT" "$REMOTE/$BRANCH" 2>/dev/null; then
    echo "  WARNING: ${COMMIT:0:8} is not on $REMOTE/$BRANCH -- deploying unpushed code"
  fi
fi

say "Running tests locally"
npm test

say "Checking the Pi is reachable"
ssh -o ConnectTimeout=10 -o BatchMode=yes "$PI_HOST" "test -d '$PI_DIR'" \
  || fail "Cannot reach $PI_HOST, or $PI_DIR does not exist there."

PREVIOUS="$(ssh "$PI_HOST" "cat '$PI_DIR/.deployed-commit' 2>/dev/null || echo unknown")"
echo "  currently deployed: $PREVIOUS"

# --- Locate pm2 ------------------------------------------------------------
# pm2 lives inside an nvm-managed Node, and nvm is not set up for a
# non-interactive ssh session -- that PATH gets the system /usr/bin/node
# instead, which has no pm2. Two tempting fixes are both wrong:
#
#   * Hardcoding a version path breaks the next time Node auto-updates.
#   * Following nvm's `default` alias breaks too, because `default` tracks the
#     newest installed Node and pm2 is only present in the version it was
#     installed into. (At the time of writing `default` was already two
#     versions ahead of the one holding pm2.)
#
# The systemd unit that resurrects the daemon names the Node actually running
# the service, so derive the bin directory from that. If the unit is ever
# regenerated by `pm2 startup`, this follows it automatically.

say "Locating pm2 on the Pi"
PM2_BIN_DIR="$(ssh "$PI_HOST" 'bash -s' <<'REMOTE'
set -eu
exec_path=$(systemctl cat pm2-pi.service 2>/dev/null | sed -n 's/^ExecStart=//p' | head -1 | awk '{print $1}')
bin_dir=""
case "$exec_path" in
  */lib/node_modules/pm2/bin/pm2) bin_dir="${exec_path%/lib/node_modules/pm2/bin/pm2}/bin" ;;
esac
# Fall back to the newest nvm Node that actually carries a pm2 binary.
if [ -z "$bin_dir" ] || [ ! -x "$bin_dir/pm2" ]; then
  bin_dir=$(for d in "$HOME"/.nvm/versions/node/*/bin; do
    [ -x "$d/pm2" ] && echo "$d"
  done | sort -V | tail -1)
fi
[ -n "$bin_dir" ] && [ -x "$bin_dir/pm2" ] || exit 1
echo "$bin_dir"
REMOTE
)" || fail "Could not find pm2 on $PI_HOST. Check 'systemctl cat pm2-pi.service' and that pm2 is installed in an nvm Node."

echo "  pm2: $PM2_BIN_DIR/pm2"
# Every remote command that needs pm2 (or the service's own Node) prefixes this.
REMOTE_ENV="export PATH='$PM2_BIN_DIR':\$PATH;"

# --- Sync ------------------------------------------------------------------

RSYNC_ARGS=(-az --human-readable "${EXCLUDES[@]}")
[ "$PRUNE" -eq 1 ] && RSYNC_ARGS+=(--delete)

if [ "$DRY_RUN" -eq 1 ]; then
  say "Dry run -- files that would change"
  rsync "${RSYNC_ARGS[@]}" --dry-run --itemize-changes ./ "$PI_HOST:$PI_DIR/"
  echo
  echo "Nothing was changed. Re-run without --dry-run to deploy."
  exit 0
fi

say "Syncing to $PI_HOST:$PI_DIR"
rsync "${RSYNC_ARGS[@]}" --itemize-changes ./ "$PI_HOST:$PI_DIR/"

# --- Install, verify, restart ----------------------------------------------
# Tests run again on the Pi: it's a different arch and Node build, and a green
# run here doesn't prove anything about there.

# Installing under the same Node that runs the service, not the system one a
# bare ssh session would pick up -- otherwise deps are built and tested against
# a different Node than they execute on.
say "Installing dependencies and testing on the Pi"
ssh "$PI_HOST" "$REMOTE_ENV cd '$PI_DIR' && node --version && npm ci --no-audit --no-fund && npm test"

# The commit stamp is written only after the restart succeeds. Writing it first
# meant a failed restart left the Pi claiming to run code it wasn't running.
say "Restarting $PM2_APP"
ssh "$PI_HOST" "$REMOTE_ENV cd '$PI_DIR' && pm2 restart '$PM2_APP' --update-env && pm2 save --force" \
  || fail "pm2 restart failed. The new files are on the Pi but the old code is still running, and .deployed-commit is unchanged."

ssh "$PI_HOST" "cd '$PI_DIR' && printf '%s\n' '$COMMIT' > .deployed-commit"

say "Verifying"
sleep 5
# pm2 sometimes prefixes jlist with update banners, so slice out the JSON array
# rather than parsing the whole stream.
STATUS="$(ssh "$PI_HOST" "$REMOTE_ENV pm2 jlist" 2>/dev/null | node -e "
  let raw='';
  process.stdin.on('data', d => raw += d);
  process.stdin.on('end', () => {
    try {
      const json = raw.slice(raw.indexOf('['), raw.lastIndexOf(']') + 1);
      const app = JSON.parse(json).find(a => a.name === '$PM2_APP');
      if (!app) return console.log('missing');
      console.log(app.pm2_env.status + ' restarts=' + app.pm2_env.restart_time);
    } catch (e) {
      console.log('unparseable');
    }
  });
" || echo "unknown")"
echo "  pm2: $STATUS"
case "$STATUS" in
  online*) ;;
  *) fail "App is not online after restart. Check: ssh $PI_HOST 'pm2 logs $PM2_APP --lines 50'" ;;
esac

say "Recent log output"
ssh "$PI_HOST" "$REMOTE_ENV pm2 logs '$PM2_APP' --lines 25 --nostream" || true

printf '\n\033[32mDeployed %s -> %s (was %s)\033[0m\n' \
  "${COMMIT:0:8}" "$PI_HOST:$PI_DIR" "${PREVIOUS:0:8}"
printf 'Rollback: git checkout %s && ./deploy.sh\n' "${PREVIOUS:0:8}"
